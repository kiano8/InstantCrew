-- Cebu City -> Cebu, Manila -> Metro Manila, and the places under them gain their region.
UPDATE jobs SET city = CASE lower(trim(city))
    WHEN 'cebu city' THEN 'Cebu'
    WHEN 'manila' THEN 'Metro Manila'
    WHEN 'mandaue' THEN 'Mandaue, Cebu'
    WHEN 'lapu-lapu city' THEN 'Lapu-Lapu, Cebu'
    WHEN 'makati city' THEN 'Makati, Metro Manila'
    WHEN 'quezon city' THEN 'Quezon City, Metro Manila'
    WHEN 'caloocan' THEN 'Caloocan, Metro Manila'
    WHEN 'las piñas' THEN 'Las Piñas, Metro Manila'
    WHEN 'malabon' THEN 'Malabon, Metro Manila'
    WHEN 'mandaluyong' THEN 'Mandaluyong, Metro Manila'
    WHEN 'marikina' THEN 'Marikina, Metro Manila'
    WHEN 'muntinlupa' THEN 'Muntinlupa, Metro Manila'
    WHEN 'navotas' THEN 'Navotas, Metro Manila'
    WHEN 'parañaque' THEN 'Parañaque, Metro Manila'
    WHEN 'pasay' THEN 'Pasay, Metro Manila'
    WHEN 'pasig' THEN 'Pasig, Metro Manila'
    WHEN 'san juan' THEN 'San Juan, Metro Manila'
    WHEN 'taguig' THEN 'Taguig, Metro Manila'
    WHEN 'valenzuela' THEN 'Valenzuela, Metro Manila'
    ELSE city END;

